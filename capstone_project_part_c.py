def fill_and_get_medians(raw_df, medians=None):
    """
    Fills missing values for distance_km, parcel_weight_kg, and declared_value_inr
    using provided medians or computing them from the DataFrame.
    Returns the filled DataFrame and the dictionary of medians.
    """
    cols_to_fill = ['distance_km', 'parcel_weight_kg', 'declared_value_inr']

    # If medians dictionary is not provided, compute them from the non-missing values
    if medians is None:
        medians = {}
        for col in cols_to_fill:
            if col in raw_df.columns:
                medians[col] = round(float(raw_df[col].median()),4)
            else:
                medians[col] = 0.0  # Fallback if column is missing entirely

    # Fill missing values using the medians dictionary
    for col in cols_to_fill:
        if col in raw_df.columns and col in medians:
            raw_df[col] = raw_df[col].fillna(medians[col])

    return raw_df, medians

