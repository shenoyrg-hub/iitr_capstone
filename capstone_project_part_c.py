    engineered_df = build_features(clean_new_df, hubs_df)

    # 4. Arrange columns strictly by feature_order.csv
    X_new = engineered_df[feature_order]

    # 5. Predict probabilities and flag delays
    probs = model.predict_proba(X_new)[:, 1]
    engineered_df["delay_probability"] = np.round(probs, 4)
    engineered_df["flagged"] = (engineered_df["delay_probability"] >= threshold).astype(int)

    # 6. Join hub segment information
    # Preserve original ordering of new_shipments.csv
    scored_df = engineered_df.merge(
        hub_segments_df[["hub_id", "segment"]],
        on="hub_id",
        how="left"
    )

    # 7. Compute operational action
    scored_df["action"] = scored_df.apply(determine_action, axis=1)

    # 8. Select and save required final output columns
    output_cols = [
        "shipment_id",
        "hub_id",
        "segment",
        "delay_probability",
        "flagged",
        "action"
    ]
    final_output = scored_df[output_cols]

    output_path = Path("outputs/new_shipment_actions.csv")
    final_output.to_csv(output_path, index=False)

    print(f"Successfully generated {output_path} ({len(final_output)} rows scored).")
    print(final_output.head(24))

