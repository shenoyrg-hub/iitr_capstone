PROMISED_HOURS = {"Express": 36, "Standard": 60, "Economy": 96}



def build_features(clean: pd.DataFrame, hubs: pd.DataFrame) -> pd.DataFrame:
  """Merges hub data and engineers required feature columns for shipment delay intelligence.

  Excludes delivery_hours so it works on both historical and un-delivered new
  parcels.
  """
  # 1. Attach hub columns via left merge on hub_id
  df = clean.merge(hubs, on="hub_id", how="left")

  # 2. promised_hours from PROMISED_HOURS mapping
  df["promised_hours"] = df["service_type"].map(PROMISED_HOURS).astype(int)

  # 3. is_cod: 1 when payment_mode is COD (case-insensitive check), else 0 (Unknown gives 0)
  df["is_cod"] = (
      df["payment_mode"].astype(str).str.strip().str.title() == "Cod"
  ).astype(int)

  # 4. is_weekend: 1 when dispatch day is Saturday (5) or Sunday (6), else 0
  df["dispatch_time"] = pd.to_datetime(df["dispatch_time"], errors="coerce")
  df["is_weekend"] = (df["dispatch_time"].dt.dayofweek >= 5).astype(int)

  # 5. dispatch_hour: integer hour of the dispatch timestamp
  df["dispatch_hour"] = df["dispatch_time"].dt.hour.astype(int)

  # 6. log_declared_value: natural log of declared_value_inr
  df["log_declared_value"] = np.log(df["declared_value_inr"])

  return df

