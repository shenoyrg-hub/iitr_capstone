def clean_shipments(raw_df, medians):
    """
    Cleans raw shipment data using stored medians for imputation.
    """
    df = raw_df.drop_duplicates().copy()

    # Standardize service_type
    df["service_type"] = df["service_type"].astype(str).str.strip().str.title()

    # Fill missing payment_mode with 'Unknown' and standardize casing
    df["payment_mode"] = df["payment_mode"].fillna("Unknown").astype(str).str.strip().str.title()

    # Clean declared_value (remove currency symbols and commas)
    if "declared_value" in df.columns:
        df["declared_value_inr"] = (
            df["declared_value"].astype(str)
            .str.replace("₹", "", regex=False)
            .str.replace(",", "", regex=False)
            .str.strip()
            .astype(float)
        )
        df = df.drop(columns=["declared_value"])

    # Convert dispatch_time to datetime
    df["dispatch_time"] = pd.to_datetime(df["dispatch_time"], errors="coerce")

    # Handle scanner-fault sentinels in parcel_weight_kg (> 100 kg)
    df["parcel_weight_kg"] = pd.to_numeric(df["parcel_weight_kg"], errors="coerce")
    df.loc[df["parcel_weight_kg"] > 100, "parcel_weight_kg"] = np.nan

    # Impute missing values using stored medians dictionary
    cols_to_fill = ["distance_km", "parcel_weight_kg", "declared_value_inr"]
    for col in cols_to_fill:
        if col in df.columns and col in medians:
            df[col] = df[col].fillna(medians[col])

    return df

def build_features(clean, hubs):
    """
    Merges hub data and engineers required feature columns.
    """
    PROMISED_HOURS = {"Express": 36, "Standard": 60, "Economy": 96}

    df = clean.merge(hubs, on="hub_id", how="left")
    df["promised_hours"] = df["service_type"].map(PROMISED_HOURS).astype(int)
    df["is_cod"] = (df["payment_mode"].astype(str).str.strip().str.title() == "Cod").astype(int)
    df["is_weekend"] = (df["dispatch_time"].dt.dayofweek >= 5).astype(int)
    df["dispatch_hour"] = df["dispatch_time"].dt.hour.astype(int)
    df["log_declared_value"] = np.log(df["declared_value_inr"])

    return df

